export const GLYPH_HEIGHT = 7;
const LETTER_GAP = 1;
/** Empty art pixels between two lines of text. */
export const LINE_GAP = 3;

function glyph(ch: string): string[] {
  return (GLYPHS[ch.toUpperCase()] ?? GLYPHS['?']).split(' ');
}

/** Renders one line of text into pixel rows ('#' ink, '.' empty). */
function lineRows(text: string): string[] {
  const rows = new Array<string>(GLYPH_HEIGHT).fill('');
  [...text].forEach((ch, i) => {
    const g = glyph(ch);
    for (let r = 0; r < GLYPH_HEIGHT; r++) {
      rows[r] += (i > 0 ? '.'.repeat(LETTER_GAP) : '') + g[r];
    }
  });
  return rows;
}

/** Renders text, honouring '\n', into equal-width pixel rows. */
export function textRows(text: string): string[] {
  const lines = text.split('\n').map(lineRows);
  const width = Math.max(...lines.map(l => l[0].length));
  const out: string[] = [];
  lines.forEach((rows, i) => {
    if (i > 0) {
      for (let g = 0; g < LINE_GAP; g++) {
        out.push('.'.repeat(width));
      }
    }
    rows.forEach(row => out.push(row.padEnd(width, '.')));
  });
  return out;
}

/** Width in art pixels of a single line, without rendering it. */
export function textWidth(text: string): number {
  return [...text].reduce(
    (sum, ch, i) => sum + glyph(ch)[0].length + (i > 0 ? LETTER_GAP : 0),
    0,
  );
}
